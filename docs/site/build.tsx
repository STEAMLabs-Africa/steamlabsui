// ---------------------------------------------------------------- tiny highlighter

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
function highlight(code: string, lang: "tsx" | "html" | "sh" | "css"): string {
  const rules: [RegExp, string][] =
    lang === "sh"
      ? [[/#[^\n]*/y, "c"], [/"[^"]*"|'[^']*'/y, "s"], [/\b(?:npm|bun|bunx|git|cd|mkdir|node)\b/y, "k"]]
      : lang === "css"
        ? [[/\/\*[\s\S]*?\*\//y, "c"], [/"[^"]*"/y, "s"], [/@[a-z-]+/y, "k"]]
        : [
            [/\/\/[^\n]*|\{\/\*[\s\S]*?\*\/\}|<!--[\s\S]*?-->/y, "c"],
            [/`[^`]*`|"[^"]*"|'[^']*'/y, "s"],
            [/<\/?[A-Za-z][\w.]*/y, "t"],
            [/\b(?:import|from|export|const|let|return|function|true|false|null|undefined|await|async|new)\b/y, "k"],
            [/\b[a-zA-Z]+(?==)/y, "a"],
          ];
  let i = 0;
  let html = "";
  outer: while (i < code.length) {
    for (const [re, cls] of rules) {
      re.lastIndex = i;
      const m = re.exec(code);
      if (m && m[0].length) {
        html += `<span class="tk-${cls}">${esc(m[0])}</span>`;
        i += m[0].length;
        continue outer;
      }
    }
    html += esc(code[i]!);
    i++;
  }
  return html;
}

/** Pretty-prints the server-rendered HTML just enough to read in the code panel. */
function formatHtml(h: string): string {
  let depth = 0;
  return h
    .replace(/></g, ">\n<")
    .split("\n")
    .map((line) => {
      if (/^<\//.test(line)) depth = Math.max(0, depth - 1);
      const outLine = "  ".repeat(depth) + line;
      if (/^<[a-z][^>]*[^/]>$/i.test(line) && !/^<(input|img|hr|br|path|circle)\b/i.test(line) && !/<\//.test(line)) depth++;
      return outLine;
    })
    .join("\n");
}

